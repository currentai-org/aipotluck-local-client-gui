#!/usr/bin/env python3
"""Sync the Alpha design system from aipotluck.org into ui/src/design/.

Upstream (currentai-org/aipotluck.org, web/src/lib/alpha-ds) is the source of truth. Its build emits
`tokens/generated/tokens.css` -- every token as a CSS custom property, colours as
`light-dark(oklch(...), oklch(...))`. A webview renders that natively, so unlike the Android port
(which has to translate OKLCH to Compose colours) this copies the file verbatim: there is no
translation step that could drift.

Also copied: `tokens/base.css` (the .ds-root base layer), the favicon (app icon source), and the
Remix Icon paths listed in ICONS (fetched from the Iconify API, which serves Remix Icon's own data,
the library the spec mandates). Fonts are OFL and live in ui/src/design/fonts/ (see its README).

    tools/design/sync-alpha.py <aipotluck.org checkout> [--offline]
    tools/design/sync-alpha.py --icons-only

Writes ui/src/design/{tokens.css,base.css,icons.ts,SOURCE.json} and src-tauri/icons/source.svg.
--icons-only rewrites icons.ts alone (after adding a name to ICONS), leaving the tokens and the
recorded aipotluck.org commit exactly as they were.
Never writes to the aipotluck.org checkout.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import subprocess
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "ui" / "src" / "design"

# Every icon the UI uses. Line = default; fill only for the one primary/destructive action (spec §5).
ICONS = [
    "checkbox-circle-fill",
    "error-warning-line",
    "clipboard-line",
    "external-link-line",
    "logout-box-r-line",
    "cpu-line",
    "download-2-line",
    "refresh-line",
    "delete-bin-line",
    "link",
    "server-line",
    "loader-4-line",
    "computer-line",
    "arrow-right-line",
    "arrow-left-line",
    "settings-3-line",
    "check-line",
]


def _sha(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _git(repo: pathlib.Path, *args: str) -> str | None:
    try:
        return subprocess.run(
            ["git", "-C", str(repo), *args], capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def fetch_icons() -> dict[str, str]:
    url = "https://api.iconify.design/ri.json?icons=" + ",".join(ICONS)
    # Iconify's CDN 403s urllib's default User-Agent.
    req = urllib.request.Request(url, headers={"User-Agent": "aipotluck-local-client-gui/sync-alpha"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        data = json.load(resp)
    out = {}
    for name in ICONS:
        body = data["icons"].get(name, {}).get("body")
        if not body:
            raise SystemExit(f"icon {name!r} not found in Remix Icon")
        paths = re.findall(r'\bd="([^"]+)"', body)
        if len(paths) != 1:
            raise SystemExit(f"icon {name!r}: expected one path, got {len(paths)}")
        out[name] = paths[0]
    return out


def write_icons() -> None:
    icons = fetch_icons()
    lines = [
        "// GENERATED by tools/design/sync-alpha.py from Remix Icon (via Iconify) -- do not edit.",
        "// 24x24 viewBox, fill=currentColor outlines; never add a stroke (design-system.md §5).",
        "export const icons = {",
    ]
    lines += [f"  {json.dumps(k)}: {json.dumps(v)}," for k, v in icons.items()]
    lines += ["} as const;", "", "export type IconName = keyof typeof icons;", ""]
    (OUT / "icons.ts").write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("web_repo", type=pathlib.Path, nargs="?", help="aipotluck.org checkout")
    ap.add_argument("--offline", action="store_true", help="skip refetching icons")
    ap.add_argument("--icons-only", action="store_true", help="only refetch icons into icons.ts")
    args = ap.parse_args()
    if args.icons_only:
        write_icons()
        print(f"wrote {len(ICONS)} icons into {(OUT / 'icons.ts').relative_to(ROOT)}")
        return 0
    if args.web_repo is None:
        ap.error("web_repo is required unless --icons-only")

    ds = args.web_repo / "web" / "src" / "lib" / "alpha-ds"
    tokens = ds / "tokens" / "generated" / "tokens.css"
    base = ds / "tokens" / "base.css"
    favicon = args.web_repo / "web" / "static" / "favicon.svg"
    for p in (tokens, base, favicon):
        if not p.exists():
            print(f"missing upstream file: {p}", file=sys.stderr)
            return 2

    OUT.mkdir(parents=True, exist_ok=True)
    header = "/* GENERATED by tools/design/sync-alpha.py from aipotluck.org {rel} -- do not edit. */\n"
    (OUT / "tokens.css").write_text(header.format(rel="web/src/lib/alpha-ds/tokens/generated/tokens.css") + tokens.read_text(), encoding="utf-8")
    (OUT / "base.css").write_text(header.format(rel="web/src/lib/alpha-ds/tokens/base.css") + base.read_text(), encoding="utf-8")
    icon_dir = ROOT / "src-tauri" / "icons"
    icon_dir.mkdir(parents=True, exist_ok=True)
    (icon_dir / "source.svg").write_text(favicon.read_text(), encoding="utf-8")

    if not args.offline:
        write_icons()

    source = {
        "repo": "currentai-org/aipotluck.org",
        "commit": _git(args.web_repo, "rev-parse", "HEAD"),
        "subject": _git(args.web_repo, "log", "-1", "--format=%s"),
        "files": {
            "tokens.css": _sha(tokens),
            "base.css": _sha(base),
            "favicon.svg": _sha(favicon),
            "design-system.md": _sha(args.web_repo / "web" / "src" / "lib" / "chat" / "design-system.md"),
        },
    }
    (OUT / "SOURCE.json").write_text(json.dumps(source, indent=2) + "\n", encoding="utf-8")
    print(f"synced Alpha DS from {source['commit'][:10] if source['commit'] else '?'} into {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
